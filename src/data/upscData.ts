export const isUPSCBook = (bookId: string): boolean => {
  return Boolean(UPSC_SYLLABUS_BOOKS[bookId]);
};

export const getUPSCBookInfo = (bookId: string): UPSCBookInfo | undefined => {
  return UPSC_SYLLABUS_BOOKS[bookId];
};

export const getAllUPSCBookIds = (): string[] => {
  return Object.keys(UPSC_SYLLABUS_BOOKS);
};

export const getUPSCBooksByPaper = (paper: UPSCPaper): UPSCBookInfo[] => {
  return Object.values(UPSC_SYLLABUS_BOOKS).filter((b) => b.paper === paper);
};

export const getAnnotationsForChapter = (bookId: string, chapterId: string): UPSCAnnotation[] => {
  const book = UPSC_SYLLABUS_BOOKS[bookId];
  if (!book || !book.annotations) return [];
  return book.annotations.filter((a) => a.chapterId === chapterId);
};
