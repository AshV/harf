export type UPSCPaper = 'Paper 1' | 'Paper 2 (पद्य)' | 'Paper 2 (गद्य)' | 'State PCS / NET';

export interface UPSCPYQ {
  year: number;
  exam: 'UPSC CSE' | 'UPPSC' | 'BPSC' | 'MPPSC' | 'UGC-NET';
  paper: 'Paper 1' | 'Paper 2';
  question: string;
  marks?: number;
  dimensions?: string[];
  keyQuotes?: string[];
}

export interface UPSCQuote {
  quote: string;
  speakerOrContext: string;
  theme: string;
  significance: string;
}

export interface UPSCAnnotation {
  id: string;
  chapterId: string;
  blockId?: string; // specific block if targeted
  targetSnippet?: string; // text prefix for matching
  title: string;
  context: string; // संदर्भ व प्रसंग (Prasang)
  explanation: string; // भावार्थ व व्याख्या (Vyakhya)
  vishesh: string[]; // विशेष / शिल्प / रस / अलंकार / अंक-प्रदायक बिंदु (Vishesh)
  glossary?: ({ word: string; meaning: string } | string)[]; // क्लिष्ट शब्दार्थ
  pyqRef?: string; // e.g. "UPSC 2019, 2022 में पूछा गया"
}

